/**
 * CONSTITUTION LINT — surface collection.
 *
 * Two layers, because copy lives in two places:
 *
 *   Layer A (`copySurfaces`) walks the *imported* copy objects. Precise: a
 *   string here is by definition a string the reader can see, and a code
 *   comment or a `!==` operator can never reach it.
 *
 *   Layer B (`sourceSurfaces`) scans page/component source for hard-coded
 *   literals and JSX text, because app/(site)/[locale]/page.tsx and the result
 *   page still carry a few hundred characters of Chinese written straight into
 *   JSX. Comments and strings are separated by a real scanner, then obvious
 *   code literals (class lists, hrefs, ids) are filtered out.
 *
 * A third source of public text, `content/singapore-guide/embed.*.html`, is
 * generated by the external tw2sg pipeline and must never be hand-edited; it is
 * linted as visible prose only (script, style and comments stripped) so that a
 * regression there is still reported, and the fix goes upstream.
 */
