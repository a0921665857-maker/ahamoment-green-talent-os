const HERE = path.dirname(fileURLToPath(import.meta.url));
export const REPO_ROOT = path.resolve(HERE, '..', '..');

/**
 * Directories scanned for hard-coded copy, and the ones deliberately left out.
 */
export const SOURCE_ROOTS = ['app', 'components'];
export const SOURCE_EXCLUDED: { match: (rel: string) => boolean; why: string }[] = [
  {
    match: (rel) => rel.startsWith('app/api/'),
    why: 'Route handlers, not rendered pages. Also fenced off this round by an unrelated security workstream — a finding here could not be fixed anyway, so it is reported by the CLI (--include-api) rather than failing the suite.',
  },
  {
    match: (rel) => rel.startsWith('components/admin/') || rel.includes('/admin/'),
    why: 'Admin console. Only Michael sees it; the calm-premium copy rules are about the reader-facing product.',
  },
  {
    match: (rel) => rel.endsWith('.test.ts') || rel.endsWith('.test.tsx'),
    why: 'Tests quote violating strings on purpose.',
  },
];

function listFiles(dir: string, acc: string[] = []): string[] {
  if (!fs.existsSync(dir)) return acc;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (['node_modules', '.next', '.git'].includes(entry.name)) continue;
      listFiles(full, acc);
    } else if (/\.(tsx?|mts)$/.test(entry.name)) acc.push(full);
  }
  return acc;
}

interface Literal {
  text: string;
  line: number;
}

/**
 * Character scanner rather than a regex, because the naive version breaks on
 * three things this codebase is full of: `//` inside a URL string, `'` inside a
 * Chinese sentence, and — the one that actually bit — a backtick inside a
 * regex literal (`components/JudgmentMarkdown.tsx` matches inline code with
 * /`([^`]+)`/). Mistaking that backtick for a template literal swallowed the
 * next forty lines of code and reported its `!==` operators as exclamation
 * marks in the copy. So regex literals are skipped explicitly.
 *
 * Returns string/template literals with comments and regexes removed.
 */
export function extractLiterals(src: string): Literal[] {
  const out: Literal[] = [];
  let i = 0;
  let line = 1;
  const n = src.length;
  const codeOnly: string[] = [];

  /** `/` starts a regex only where a value may begin, never after an operand. */
  const regexCanStart = (): boolean => {
    for (let j = codeOnly.length - 1; j >= 0; j--) {
      const c = codeOnly[j];
      if (/\s/.test(c)) continue;
      if (/[)\]}\w$]/.test(c)) {
        const tail = codeOnly.slice(Math.max(0, j - 8), j + 1).join('');
        return /\b(?:return|typeof|case|in|of|new|delete|void|do|else)$/.test(tail);
      }
      return true;
    }
    return true;
  };

  while (i < n) {
    const ch = src[i];
    const next = src[i + 1];

    if (ch === '\n') {
      line++;
      i++;
      codeOnly.push('\n');
      continue;
    }
    if (ch === '/' && next !== '/' && next !== '*' && regexCanStart()) {
      i++;
      let inClass = false;
      while (i < n) {
        if (src[i] === '\\') {
          i += 2;
          continue;
        }
        if (src[i] === '[') inClass = true;
        else if (src[i] === ']') inClass = false;
        else if (src[i] === '/' && !inClass) {
          i++;
          break;
        } else if (src[i] === '\n') {
          // Not a regex after all (they cannot span lines); bail out safely.
          break;
        }
        i++;
      }
      while (i < n && /[a-z]/.test(src[i])) i++; // flags
      codeOnly.push(' ');
      continue;
    }
    if (ch === '/' && next === '/') {
      while (i < n && src[i] !== '\n') i++;
      continue;
    }
    if (ch === '/' && next === '*') {
      i += 2;
      while (i < n && !(src[i] === '*' && src[i + 1] === '/')) {
        if (src[i] === '\n') line++;
        i++;
      }
      i += 2;
      continue;
    }
    if (ch === '"' || ch === "'" || ch === '`') {
      const quote = ch;
      const startLine = line;
      i++;
      let buf = '';
      while (i < n) {
        if (src[i] === '\\') {
          buf += src[i + 1] ?? '';
          i += 2;
          continue;
        }
        if (src[i] === quote) {
          i++;
          break;
        }
        if (src[i] === '\n') line++;
        // template placeholders are code, not copy
        if (quote === '`' && src[i] === '$' && src[i + 1] === '{') {
          let depth = 1;
          i += 2;
          while (i < n && depth > 0) {
            if (src[i] === '{') depth++;
            else if (src[i] === '}') depth--;
            else if (src[i] === '\n') line++;
            i++;
          }
          continue;
        }
        buf += src[i];
        i++;
      }
      out.push({ text: buf, line: startLine });
      codeOnly.push(' ');
      continue;
    }
    codeOnly.push(ch);
    i++;
  }

  // JSX text nodes: whatever sits between tags once strings and comments are
  // gone. `>` and `<` are also operators and generic brackets, so a candidate is
  // only accepted when it reads as prose — no statement punctuation, no arrow,
  // no comparison. Without this filter `(l) => l.code === x)!;` was reported as
  // an exclamation mark in the reader-facing copy.
  const stripped = codeOnly.join('');
  const jsxText = /(?<=>)([^<>{}]+)(?=<)/g;
  let m: RegExpExecArray | null;
  while ((m = jsxText.exec(stripped)) !== null) {
    const text = m[1].trim();
    if (text.length === 0 || !/[\p{L}]/u.test(text)) continue;
    if (/[;=()[\]|&$\\]|=>|\?\?|\.\.\./.test(text)) continue;
    const lineNo = stripped.slice(0, m.index).split('\n').length;
    out.push({ text, line: lineNo });
  }

  return out;
}

/**
 * Literals that are code wearing quotes: Tailwind class lists, hrefs, keys,
 * date formats. Excluding them is not a copy exemption — they are not copy.
 */
export function looksLikeCode(text: string): boolean {
  const t = text.trim();
  if (t.length === 0) return true;
  if (/^[\w./#@:?&=%+~-]*$/.test(t)) return true; // single token: id, href, class, key
  if (/^https?:\/\//.test(t)) return true;
  const tokens = t.split(/\s+/);
  const codey = tokens.filter((tok) => /^[a-z0-9:[\]/.%_-]+$/.test(tok) && /[-:[\]/]/.test(tok)).length;
  if (tokens.length >= 2 && codey / tokens.length > 0.6) return true; // class list
  return false;
}

export function sourceSurfaces(opts: { includeApi?: boolean } = {}): Surface[] {
  const out: Surface[] = [];
  for (const root of SOURCE_ROOTS) {
    for (const file of listFiles(path.join(REPO_ROOT, root))) {
      const rel = path.relative(REPO_ROOT, file).split(path.sep).join('/');
      const excluded = SOURCE_EXCLUDED.find((e) => e.match(rel));
      if (excluded && !(opts.includeApi && rel.startsWith('app/api/'))) continue;
      const src = fs.readFileSync(file, 'utf8');
      for (const lit of extractLiterals(src)) {
        if (looksLikeCode(lit.text)) continue;
        out.push({
          path: `${rel}:${lit.line}`,
          text: lit.text,
          selling: /services|offer|payment|Cta/i.test(rel),
          // Hard-coded page copy is the product speaking; the two knowledge
          // pages that render corpus data pull their prose from content/.
          marketing: !/judgment|salary|cost-of-living|singapore/i.test(rel),
        });
      }
    }
  }
  return out;
}

/* --------------------------- layer C: html fragments -------------------------- */

export const HTML_FRAGMENTS = [
  'content/singapore-guide/embed.zh-TW.html',
  'content/singapore-guide/embed.en.html',
];

/** Visible prose only: script, style, comments and tags removed. */
export function htmlVisibleText(html: string): string {
  return html
    .replace(/<script[\s\S]*?<\/script>/gi, ' ')
    .replace(/<style[\s\S]*?<\/style>/gi, ' ')
    .replace(/<!--[\s\S]*?-->/g, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/[ \t]+/g, ' ');
}

export function fragmentSurfaces(): Surface[] {
  return HTML_FRAGMENTS.filter((rel) => fs.existsSync(path.join(REPO_ROOT, rel))).map((rel) => ({
    path: rel,
    text: htmlVisibleText(fs.readFileSync(path.join(REPO_ROOT, rel), 'utf8')),
    selling: false,
    // A step-by-step guide to official Singapore procedures, not a pitch.
    marketing: false,
  }));
}

export function allSurfaces(opts: { includeApi?: boolean } = {}): Surface[] {
  return [...copySurfaces(), ...sourceSurfaces(opts), ...fragmentSurfaces()];
}
