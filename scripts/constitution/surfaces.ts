export interface Surface {
  /** Dotted path, used as the finding location. */
  path: string;
  text: string;
  /** Selling surfaces are the only ones price-checked. See LintOptions. */
  selling: boolean;
  /** False for the knowledge corpora; see KNOWLEDGE_CORPORA below. */
  marketing: boolean;
}

/* --------------------------- documented exemptions --------------------------- */

/**
 * Every entry is a claim that the strings under it are NOT reader-facing public
 * copy. None of them is "this is too noisy to fix".
 */
export const SKIPPED_SUBTREES: { match: (p: string) => boolean; why: string }[] = [
  {
    match: (p) => ARCHIVED_OFFER_IDS.some((id) => p.includes(`paidOffers.offers.${id}`)),
    why: 'Offers retired by Gate 8. lib/services.ts keeps their copy only so historical DB rows render in admin; no public surface can reach them, and their old price strings (US$39, NT$1,200…) are deliberately frozen history.',
  },
  {
    match: (p) => /\.(url|href|slug|id|token|image|icon|src|utm[A-Za-z]*)$/.test(p),
    why: 'Identifiers and links, not prose. A URL is allowed to contain an offer id or an exclamation mark without addressing the reader.',
  },
  {
    match: (p) => p.startsWith('greenJobs.jobs.') && /\.(org|source|location)$/.test(p),
    why: 'Third-party employer and board names, quoted verbatim. Michael does not author them and must not rewrite them.',
  },
];

/* ------------------------------- generic walker ------------------------------ */

/**
 * Surfaces that teach rather than sell. They quote assurance levels, contract
 * clauses and government figures, so a word like 保證 does real work there; the
 * lint keeps its outcome-promise trigger on them but drops the blanket ban.
 * Everything not listed here is persuasion copy by default — the safe direction
 * for a rule set whose whole purpose is to catch marketing drift.
 */
export const KNOWLEDGE_CORPORA = [
  'judgment',
  'costOfLiving',
  'salaryReports',
  'salaryIndexCopy',
  'sgOfficialCopy',
  'greenJobs',
  'marketPulse',
  'levelupReports',
  'singaporeGuideCopy',
];

function isKnowledge(rootPath: string): boolean {
  const root = rootPath.split(/[.[]/)[0];
  return KNOWLEDGE_CORPORA.includes(root);
}

function walk(node: unknown, prefix: string, out: Surface[], selling: boolean, marketing: boolean) {
  if (SKIPPED_SUBTREES.some((s) => s.match(prefix))) return;
  if (typeof node === 'string') {
    // Evaluated on the full dotted path, not just the module name, so that
    // `zh-TW.results.<category>.offerLine` is price-checked while the rest of
    // the report copy around it is not.
    if (node.trim().length > 0) out.push({ path: prefix, text: node, selling: selling || sellingFor(prefix), marketing });
    return;
  }
  if (Array.isArray(node)) {
    node.forEach((v, i) => walk(v, `${prefix}[${i}]`, out, selling, marketing));
    return;
  }
  if (node && typeof node === 'object') {
    for (const [k, v] of Object.entries(node as Record<string, unknown>)) {
      walk(v, prefix ? `${prefix}.${k}` : k, out, selling, marketing);
    }
  }
}

/**
 * Selling surfaces: where Michael's own prices may legitimately appear, and
 * therefore the only places a wrong price is detectable as wrong. Everything
 * else on the site (salary bands, cost-of-living tables, MBA ROI inputs, the
 * judgement corpus) is full of correct money figures that have nothing to do
 * with what he charges.
 */
const SELLING_PATH_RE = /(^|\.)(paidOffers|payment|results\.[a-z_]+\.(offerLine|cta)|landing\.(services|offers|pricing))/;

function sellingFor(rootPath: string): boolean {
  return SELLING_PATH_RE.test(rootPath);
}

/* --------------------------------- layer A ---------------------------------- */

export function copySurfaces(): Surface[] {
  const out: Surface[] = [];

  for (const locale of LOCALES) {
    const c = getContent(locale) as unknown as Record<string, unknown>;
    for (const [section, value] of Object.entries(c)) {
      // The locale tree is the product's own voice end to end: landing, flow,
      // report, offers, emails. All of it is persuasion copy.
      walk(value, `${locale}.${section}`, out, sellingFor(section), true);
    }
  }

  const standalone: Record<string, unknown> = {
    costOfLiving,
    greenJobs,
    greenJobsCopy,
    jdTranslatorCopy,
    levelupReports,
    marketPulse,
    mbaRoiCopy,
    navCopy,
    newsletterCopy,
    notFoundCopy,
    salaryIndexCopy,
    salaryReports,
    sampleReports,
    sgOfficialCopy,
    singaporeGuideCopy,
    judgment: judgmentData,
  };
  for (const [name, value] of Object.entries(standalone)) {
    walk(value, name, out, sellingFor(name), !isKnowledge(name));
  }

  return out;
}

/** The only prices a selling surface may print. */
export function allowedPrices(): string[] {
  const prices = new Set<string>();
  for (const id of PUBLIC_PAID_OFFER_IDS) {
    for (const market of ['tw', 'intl'] as const) prices.add(SERVICE_PRICE[id][market].display);
  }
  return [...prices];
}

